import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync, rmSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import test from 'node:test';
import { RoomService } from '../src/room/room-service.ts';
import { ProjectRegistry } from '../src/ui/project-registry.ts';
import { RoomUiApplication } from '../src/ui/application.ts';
import { WorkbenchStore } from '../src/ui/workbench-store.ts';
import { DesktopProcesses, liveOwnedProcesses, type ProcessEntry } from '../src/ui/desktop-processes.ts';
import { EXECUTOR, PLANNER, WORKER, makeQuestion, makeTask } from './fixtures.ts';

for (const initial of ['running', 'decision_requested', 'cancel_requested'] as const) test(`recovery checks ownership and preserves ${initial} semantics without replay`, async () => {
  const root = mkdtempSync(join(tmpdir(), 'room-recovery-'));
  const git = (...args: string[]) => execFileSync('git', args, { cwd: root, stdio: 'pipe' });
  git('init', '-b', 'main'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.invalid');
  writeFileSync(join(root, 'file.txt'), 'initial'); git('add', '.'); git('commit', '-m', 'test: seed');
  const dbPath = join(root, 'room.sqlite');
  const db = new DatabaseSync(dbPath);
  const service = new RoomService(db);
  service.createRoom('room-1', PLANNER);
  service.transitionToArchitectureReview('room-1', PLANNER); service.transitionToWaitingForUserConfirmation('room-1', PLANNER);
  service.submitTask(makeTask(), PLANNER);
  service.claimRunAttempt({ room_id: 'room-1', run_id: 'run-1', attempt_id: 'attempt-1', worktree_path: root }, EXECUTOR);
  if (initial === 'decision_requested') service.askQuestion(makeQuestion(), WORKER);
  if (initial === 'cancel_requested') service.cancelRun({ room_id: 'room-1', run_id: 'run-1', confirmed_by_user: true, reason: 'Stop before restart' }, PLANNER);
  const store = new WorkbenchStore(db, 'room-1');
  const task = store.save({ title: 'Recover', goal: 'Keep changes', mode: 'task', verification: 'standard', source_ids: [] });
  store.update(task.id, { run_id: 'run-1', task_id: 'task-1' });
  writeFileSync(join(root, 'file.txt'), 'unfinished work');
  const logs = join(root, 'artifacts', 'attempt-1'); mkdirSync(logs, { recursive: true });
  writeFileSync(join(logs, 'stdout.jsonl'), JSON.stringify({ type: 'system', subtype: 'init', session_id: 'reliable-session', tools: ['mcp__agent_room__room_ask_question'] }) + '\n');
  const registry = new ProjectRegistry(join(root, 'registry.json'));
  registry.add({ project_id: 'project', name: 'Project', project_path: root, database_path: dbPath, room_id: 'room-1', control_participant_id: 'codex-app', port: null });
  let processes: ProcessEntry[] = [];
  const application = new RoomUiApplication(registry, { readProcesses: async () => processes });
  try {
    assert.equal((await application.recovery.inspect('project', task.id)).state, 'unknown');
    await assert.rejects(application.recovery.recover('project', task.id, { confirmed_by_user: true }), /归属/);
    const owners = new DesktopProcesses(db);
    owners.record('attempt:attempt-1', 'room-1', 'run-1', 8765);
    processes = [{ pid: 8766, parent_pid: 8765 }];
    assert.deepEqual(liveOwnedProcesses([owners.get('attempt:attempt-1', 'room-1')!], processes), [8766]);
    assert.equal((await application.recovery.inspect('project', task.id)).state, 'running');
    await assert.rejects(application.recovery.recover('project', task.id, { confirmed_by_user: true }), /仍在运行/);
    assert.equal(service.getAttempt('attempt-1')?.status, initial);
    processes = [];
    assert.equal((await application.recovery.inspect('project', task.id)).state, 'stopped');
    await application.recovery.recover('project', task.id, { confirmed_by_user: true });
    const attempt = service.getAttempt('attempt-1')!;
    assert.equal(attempt.status, initial === 'decision_requested' ? 'needs_decision' : initial === 'cancel_requested' ? 'canceled' : 'interrupted');
    if (initial === 'decision_requested') assert.equal(service.latestOpenQuestionForRun('run-1')?.question_id, 'question-1');
    assert.equal(attempt.process_exit_code, null);
    assert.equal(attempt.agent_session_ref, 'reliable-session');
    assert.ok(attempt.git_evidence.unstaged.includes('file.txt'));
    assert.ok(attempt.artifact_refs.includes(join(logs, 'stdout.jsonl')));
    assert.equal(readFileSync(join(root, 'file.txt'), 'utf8'), 'unfinished work');
    assert.equal(service.listAttemptsByRun('run-1').length, 1);
    assert.equal((await application.recovery.inspect('project', task.id)).state, 'inactive');
  } finally { await application.close(); db.close(); rmSync(root, { recursive: true, force: true }); }
});
